import React from 'react';
import { CardinalAvatarConfig } from '../../types';
import { generateDefaultCardinalForUser, CARDINAL_PRESETS } from '../../data/cardinalPresets';

interface CardinalAvatarRendererProps {
  avatar?: CardinalAvatarConfig | string | null;
  fallbackSeed?: { id: string; name: string };
  size?: 'xs' | 'sm' | 'md' | 'lg' | 'xl' | '2xl';
  className?: string;
  showRing?: boolean;
}

const SIZE_MAP = {
  xs: 'w-6 h-6',
  sm: 'w-8 h-8',
  md: 'w-10 h-10',
  lg: 'w-14 h-14',
  xl: 'w-20 h-20',
  '2xl': 'w-28 h-28'
};

export const CardinalAvatarRenderer: React.FC<CardinalAvatarRendererProps> = ({
  avatar,
  fallbackSeed,
  size = 'md',
  className = '',
  showRing = true
}) => {
  // Resolve avatar configuration
  let config: CardinalAvatarConfig;

  if (avatar && typeof avatar === 'object') {
    config = avatar;
  } else if (typeof avatar === 'string') {
    // If it's a string, find preset by ID or check if it's a data url
    if (avatar.startsWith('data:image/')) {
      config = {
        ...CARDINAL_PRESETS[0],
        id: 'custom-data-url',
        customDataUrl: avatar
      };
    } else {
      config = CARDINAL_PRESETS.find((p) => p.id === avatar) || CARDINAL_PRESETS[0];
    }
  } else if (fallbackSeed) {
    // Automatically generate deterministic unique cardinal for user!
    config = generateDefaultCardinalForUser(fallbackSeed.id, fallbackSeed.name);
  } else {
    config = CARDINAL_PRESETS[0];
  }

  const sizeClass = SIZE_MAP[size] || SIZE_MAP.md;

  // If a custom image Data URL was generated by the image tool, render with fallback
  if (config.customDataUrl) {
    return (
      <div
        className={`relative rounded-full overflow-hidden shrink-0 ${sizeClass} ${
          showRing ? `p-0.5 bg-gradient-to-tr ${config.borderPalette || 'from-rose-500 to-amber-500'}` : ''
        } ${className}`}
      >
        <div className="w-full h-full rounded-full overflow-hidden bg-slate-100 flex items-center justify-center">
          <img
            src={config.customDataUrl}
            alt={config.name || 'Avatar del Cardenal'}
            referrerPolicy="no-referrer"
            className="w-full h-full object-cover rounded-full"
          />
        </div>
      </div>
    );
  }

  // Pure Scalable Vector Graphic (SVG) with Wayuu Kanasü motifs and Cardinal details
  const {
    bodyColor = '#E11D48',
    crestColor = '#9F1239',
    beakColor = '#F59E0B',
    chestPattern = 'kanasu-molokonoutaya',
    patternColorPrimary = '#FBBF24',
    patternColorSecondary = '#DC2626',
    accessory = 'mochila',
    eyeExpression = 'cheerful',
    borderPalette = 'from-rose-500 via-amber-500 to-rose-600'
  } = config;

  return (
    <div
      className={`relative rounded-full shrink-0 select-none ${sizeClass} ${
        showRing ? `p-0.5 bg-gradient-to-tr ${borderPalette} shadow-xs` : ''
      } ${className}`}
      title={config.name}
    >
      <div className="w-full h-full rounded-full overflow-hidden bg-slate-900/10 flex items-center justify-center">
        <svg
          viewBox="0 0 100 100"
          className="w-full h-full rounded-full"
          xmlns="http://www.w3.org/2000/svg"
        >
          <defs>
            {/* Pattern 1: Kanasü Molokonoutaya (Caparazón de Morrocoy) */}
            <pattern id={`moloko-${config.id || 'default'}`} width="12" height="12" patternUnits="userSpaceOnUse">
              <rect width="12" height="12" fill={patternColorSecondary} />
              <polygon points="6,0 12,6 6,12 0,6" fill={patternColorPrimary} />
              <polygon points="6,3 9,6 6,9 3,6" fill={bodyColor} />
            </pattern>

            {/* Pattern 2: Kanasü Pulikerüya (Diamantes dentados) */}
            <pattern id={`pulike-${config.id || 'default'}`} width="10" height="10" patternUnits="userSpaceOnUse">
              <rect width="10" height="10" fill={patternColorPrimary} />
              <polygon points="0,0 5,5 0,10" fill={patternColorSecondary} />
              <polygon points="10,0 5,5 10,10" fill={patternColorSecondary} />
            </pattern>

            {/* Pattern 3: Kanasü Pasuatalooshi (Huellas de ave) */}
            <pattern id={`pasua-${config.id || 'default'}`} width="10" height="10" patternUnits="userSpaceOnUse">
              <rect width="10" height="10" fill={patternColorSecondary} />
              <line x1="5" y1="0" x2="5" y2="10" stroke={patternColorPrimary} strokeWidth="1.5" />
              <line x1="2" y1="3" x2="5" y2="7" stroke={patternColorPrimary} strokeWidth="1.5" />
              <line x1="8" y1="3" x2="5" y2="7" stroke={patternColorPrimary} strokeWidth="1.5" />
            </pattern>

            {/* Pattern 4: Triángulos entrelazados */}
            <pattern id={`triangles-${config.id || 'default'}`} width="8" height="8" patternUnits="userSpaceOnUse">
              <rect width="8" height="8" fill={patternColorSecondary} />
              <polygon points="0,0 8,0 4,8" fill={patternColorPrimary} />
            </pattern>

            {/* Pattern 5: Franjas tejidas */}
            <pattern id={`stripes-${config.id || 'default'}`} width="6" height="6" patternUnits="userSpaceOnUse">
              <rect width="3" height="6" fill={patternColorPrimary} />
              <rect x="3" width="3" height="6" fill={patternColorSecondary} />
            </pattern>

            {/* Background Glow Gradient */}
            <linearGradient id={`bgGrad-${config.id || 'default'}`} x1="0" y1="0" x2="0" y2="1">
              <stop offset="0%" stopColor="#FFF1F2" />
              <stop offset="100%" stopColor="#FFE4E6" />
            </linearGradient>
          </defs>

          {/* 1. Backdrop disk */}
          <circle cx="50" cy="50" r="49" fill={`url(#bgGrad-${config.id || 'default'})`} />

          {/* 2. Cardinal Crest (Penacho rojo distintivo de plumas erguidas del Cardenal Guajiro) */}
          <path
            d="M 50 14 C 47 4, 38 7, 39 18 C 39 12, 33 14, 35 24 C 33 21, 29 25, 33 33 L 48 38 Z"
            fill={crestColor}
          />
          <path
            d="M 50 12 C 45 2, 40 4, 43 16 C 41 12, 37 15, 39 23 L 48 35 Z"
            fill={bodyColor}
            opacity="0.8"
          />

          {/* 3. Cardinal Head & Body */}
          {/* Main Body */}
          <circle cx="50" cy="58" r="30" fill={bodyColor} />
          {/* Head */}
          <circle cx="48" cy="40" r="21" fill={bodyColor} />

          {/* 4. Cardinal Black Face Mask (Característica del Cardenal Guajiro) */}
          <path
            d="M 43 31 C 36 34, 35 48, 45 51 C 52 52, 57 47, 57 40 C 57 33, 50 29, 43 31 Z"
            fill="#1E293B"
          />

          {/* 5. Chest with Wayuu Woven Kanasü Pattern */}
          <path
            d="M 32 54 C 32 54, 40 50, 50 50 C 60 50, 68 54, 68 54 C 68 68, 62 82, 50 82 C 38 82, 32 68, 32 54 Z"
            fill={
              chestPattern === 'kanasu-molokonoutaya'
                ? `url(#moloko-${config.id || 'default'})`
                : chestPattern === 'kanasu-pulikeruya'
                ? `url(#pulike-${config.id || 'default'})`
                : chestPattern === 'kanasu-pasuatalooshi'
                ? `url(#pasua-${config.id || 'default'})`
                : chestPattern === 'kanasu-triangles'
                ? `url(#triangles-${config.id || 'default'})`
                : chestPattern === 'stripes'
                ? `url(#stripes-${config.id || 'default'})`
                : patternColorPrimary
            }
            stroke={patternColorSecondary}
            strokeWidth="1.5"
          />

          {/* 6. Cardinal Beak (Pico cónico dorado fuerte) */}
          <polygon
            points="38,39 20,44 38,49"
            fill={beakColor}
            stroke="#D97706"
            strokeWidth="0.8"
          />
          <polygon
            points="38,44 20,44 38,49"
            fill="#D97706"
            opacity="0.4"
          />

          {/* 7. Eyes based on expression */}
          {eyeExpression === 'cheerful' && (
            <g>
              <ellipse cx="46" cy="38" rx="3.5" ry="4.5" fill="#FFFFFF" />
              <circle cx="45" cy="38" r="2.3" fill="#0F172A" />
              <circle cx="44" cy="36.8" r="0.8" fill="#FFFFFF" />
            </g>
          )}

          {eyeExpression === 'focused' && (
            <g>
              <ellipse cx="46" cy="38" rx="3" ry="3.5" fill="#FFFFFF" />
              <circle cx="45" cy="38" r="2" fill="#0F172A" />
              {/* Focused brow line */}
              <line x1="42" y1="34" x2="48" y2="36" stroke="#FFFFFF" strokeWidth="1" strokeLinecap="round" />
            </g>
          )}

          {eyeExpression === 'proud' && (
            <g>
              {/* Confident curved eye */}
              <path d="M 43 39 Q 46 35 49 39" fill="none" stroke="#FFFFFF" strokeWidth="2.2" strokeLinecap="round" />
            </g>
          )}

          {eyeExpression === 'curious' && (
            <g>
              <ellipse cx="46" cy="37" rx="4" ry="4.5" fill="#FFFFFF" />
              <circle cx="45" cy="37" r="2.6" fill="#0F172A" />
              <circle cx="44" cy="35.5" r="1.1" fill="#FFFFFF" />
            </g>
          )}

          {/* 8. Accessories */}
          {/* Accessory: Mochila Wayuu strap and miniature pouch */}
          {accessory === 'mochila' && (
            <g>
              {/* Crossed woven strap */}
              <line
                x1="34"
                y1="46"
                x2="65"
                y2="76"
                stroke={patternColorPrimary}
                strokeWidth="4.5"
                strokeDasharray="2,2"
              />
              <line
                x1="34"
                y1="46"
                x2="65"
                y2="76"
                stroke={patternColorSecondary}
                strokeWidth="2.5"
              />
              {/* Miniature woven bag */}
              <circle cx="64" cy="74" r="7" fill={patternColorSecondary} stroke={patternColorPrimary} strokeWidth="1.5" />
              <polygon points="61,79 64,84 67,79" fill={patternColorPrimary} />
            </g>
          )}

          {/* Accessory: Sombrero Wayuu Mawisa */}
          {accessory === 'sombrero-wayuu' && (
            <g>
              {/* Straw hat brim */}
              <ellipse cx="47" cy="27" rx="20" ry="5.5" fill="#FEF3C7" stroke="#D97706" strokeWidth="1.2" />
              {/* Hat crown */}
              <path d="M 37 27 C 37 17, 57 17, 57 27 Z" fill="#FDE68A" stroke="#D97706" strokeWidth="1.2" />
              {/* Woven colorful band around crown */}
              <path d="M 37 25 Q 47 28 57 25" stroke="#E11D48" strokeWidth="2.5" fill="none" />
            </g>
          )}

          {/* Accessory: Tumuma Sacred Beads Necklace */}
          {accessory === 'tumuma-necklace' && (
            <g>
              {/* Turquoise & red sacred stones */}
              <circle cx="38" cy="51" r="2.8" fill="#06B6D4" stroke="#0891B2" strokeWidth="0.8" />
              <circle cx="43" cy="53.5" r="3.2" fill="#E11D48" stroke="#BE123C" strokeWidth="0.8" />
              <circle cx="49" cy="54.5" r="3.5" fill="#F59E0B" stroke="#D97706" strokeWidth="0.8" />
              <circle cx="55" cy="53.5" r="3.2" fill="#06B6D4" stroke="#0891B2" strokeWidth="0.8" />
              <circle cx="60" cy="51" r="2.8" fill="#E11D48" stroke="#BE123C" strokeWidth="0.8" />
            </g>
          )}

          {/* Accessory: Ceremonial Feather in Crest */}
          {accessory === 'feather-crest' && (
            <g>
              <path
                d="M 50 16 C 58 4, 66 10, 52 24 Z"
                fill="#FBBF24"
                stroke="#D97706"
                strokeWidth="1"
              />
              <line x1="51" y1="20" x2="60" y2="8" stroke="#B45309" strokeWidth="1" />
            </g>
          )}

          {/* Outer Border ring subtle detail */}
          <circle cx="50" cy="50" r="48" fill="none" stroke="#FFFFFF" strokeWidth="1.5" opacity="0.6" />
        </svg>
      </div>
    </div>
  );
};
